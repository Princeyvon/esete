export function computeDashboardMetrics(products: AgroProduct[]) {
  const totalProducts = products.length;
  const publishedProducts = products.filter((p) => p.status === "published").length;
  const draftProducts = products.filter((p) => p.status === "draft").length;
  const outOfStockProducts = products.filter((p) => p.stockStatus === "out_of_stock").length;
  const lowStockProducts = products.filter((p) => p.stockStatus === "low_stock").length;
  const inStockProducts = products.filter((p) => p.status === "published" && p.stockStatus === "in_stock").length;

  const categoryStockData = CATEGORIES.map((cat) => {
    const categoryProducts = products.filter((p) => p.category === cat);
    const availableUnits = categoryProducts.reduce((sum, p) => sum + p.stock, 0);
    const totalSkus = categoryProducts.length;
    return {
      category: cat,
      availableUnits,
      skus: totalSkus,
    };
  });

  const totalAvailableUnits = products.reduce((sum, p) => sum + p.stock, 0);
  const lowStockAttention = products.filter((p) => p.stockStatus === "low_stock");

  return {
    totalProducts,
    publishedProducts,
    draftProducts,
    outOfStockProducts,
    lowStockProducts,
    inStockProducts,
    categoryStockData,
    totalAvailableUnits,
    lowStockAttention,
  };
}

export function formatPrice(
  price: number | null,
  showPrice = true,
  currency: "ETB" | "RWF" = "ETB",
  rate = 10.5,
): string {
  if (!showPrice || price === null || price === undefined) {
    return "Contact us for price";
  }
  if (currency === "RWF") {
    const converted = Math.round(price * rate);
    return `RWF ${converted.toLocaleString("en-US")}`;
  }
  return `ETB ${price.toLocaleString("en-US")}`;
}
